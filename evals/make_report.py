"""Rebuild evals/adversarial-report.md from fresh runs.

No timestamps and no history writes: the report is a pure function of
the suites, so a diff in the file is a diff in the numbers. Run from
the repo root: python evals/make_report.py
"""

import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import run_adversarial  # noqa: E402
import run_threshold_probe as probe  # noqa: E402
import scoring  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "adversarial-report.md")


def _family_rows(attacks):
    fams = {}
    for case, _q, _o, cls in attacks:
        fam = fams.setdefault(case["family"], {"n": 0, "succeeded": 0,
                                               "blocked": 0, "evaded": 0,
                                               "inconclusive": 0})
        fam["n"] += 1
        fam[cls] += 1
    return fams


def main():
    data = run_adversarial.collect()
    seed_m = run_adversarial.metrics_for(data["seed_attacks"],
                                         data["control_benign"])
    var_m = run_adversarial.metrics_for(data["variant_attacks"],
                                        data["variant_benign"])
    lines = []
    lines.append("# Adversarial report — semantic-cache")
    lines.append("")
    lines.append("Generated by `evals/make_report.py` from fresh runs of "
                 "the seeds, variants, PAWS-style slice and threshold "
                 "probe. Scoring: `evals/scoring.py` v"
                 f"{scoring.METRICS_VERSION} (frozen). Embedder: the "
                 "repo's deterministic HashEmbedder stand-in — see "
                 "RESEARCH.md Limitations for what that bounds.")
    lines.append("")
    lines.append("## Headline metrics (threshold 0.90, the repo default)")
    lines.append("")
    lines.append("| suite | attacks | blocked | succeeded | evaded | ASR | "
                 "benign (n) | false hits | false misses | FHR | "
                 "completion |")
    lines.append("|---|---|---|---|---|---|---|---|---|---|---|")
    for name, m in (("seeds", seed_m), ("variants", var_m)):
        a, b = m["attacks"], m["benign"]
        lines.append(
            f"| {name} | {a['n']} | {a['blocked']} | {a['succeeded']} | "
            f"{a['evaded']} | {a['asr']:.1%} | {b['n']} | {b['false_hit']} | "
            f"{b['false_miss']} | "
            f"{'n/a' if b['fhr'] is None else format(b['fhr'], '.1%')} | "
            f"{b['completion']:.1%} |")
    lines.append("")
    lines.append("## Seed attacks by family")
    lines.append("")
    lines.append("| family | runs | blocked | succeeded | evaded |")
    lines.append("|---|---|---|---|---|")
    for fam, r in sorted(_family_rows(data["seed_attacks"]).items()):
        lines.append(f"| {fam} | {r['n']} | {r['blocked']} | "
                     f"{r['succeeded']} | {r['evaded']} |")
    lines.append("")
    lines.append("## Every seed run")
    lines.append("")
    lines.append("| case | class | tier | similarity | query |")
    lines.append("|---|---|---|---|---|")
    for case, query, outcome, cls in data["seed_attacks"]:
        sim = outcome["similarity"]
        sim_s = "—" if sim is None else f"{sim:.4f}"
        lines.append(f"| {case['id']} | {cls} | {outcome['tier']} | "
                     f"{sim_s} | {query['prompt']} |")
    lines.append("")
    lines.append("## PAWS-style slice (16 hand-written pairs)")
    lines.append("")
    p = data["paws_stats"]
    lines.append(f"Prediction = cache hit ↔ paraphrase. Accuracy "
                 f"{p['accuracy']:.1%} (n={p['n']}). Not-paraphrase pairs "
                 f"correctly rejected: {p['not_paraphrase_caught']}/"
                 f"{p['not_paraphrase_n']}. Paraphrase pairs correctly "
                 f"accepted: {p['paraphrase_caught']}/{p['paraphrase_n']}.")
    lines.append("")
    lines.append("| pair | label | predicted | similarity |")
    lines.append("|---|---|---|---|")
    for pair, predicted, sim in data["paws_rows"]:
        sim_s = "—" if sim is None else f"{sim:.4f}"
        lines.append(f"| {pair['id']} | {pair['label']} | "
                     f"{'paraphrase' if predicted else 'not_paraphrase'} | "
                     f"{sim_s} |")
    lines.append("")
    lines.append("## Similarity ladders (HashEmbedder, measured)")
    lines.append("")
    for length in (6, 12, 20):
        rows = probe.overlap_ladder(length)
        hits = [k for k, _s, h in rows if h]
        lines.append(f"- Overlap, {length}-token stored prompt: hits "
                     f"require sharing >= {min(hits)}/{length} tokens "
                     f"(similarity {min(s for k, s, h in rows if h):.4f}); "
                     f"sharing {min(hits) - 1} scores "
                     f"{max(s for k, s, h in rows if not h):.4f} and "
                     f"misses. No similarity between those two values is "
                     f"attainable at this length.")
    rows = probe.append_ladder()
    hits = [m for m, _s, h in rows if h]
    lines.append(f"- Append, 12-token stored prompt: up to "
                 f"+{max(hits)} arbitrary tokens still hit "
                 f"({[s for m, s, h in rows if m == max(hits)][0]:.4f}); "
                 f"+{max(hits) + 1} misses "
                 f"({[s for m, s, h in rows if m == max(hits) + 1][0]:.4f}).")
    disjoint = probe.overlap_ladder(20)[-1][1]
    lines.append(f"- Collision floor: two fully disjoint 20-token "
                 f"prompts score {disjoint:.4f}, not 0 — 256 hash slots "
                 f"collide, so 'no shared words' is not 'zero "
                 f"similarity' in this embedder.")
    lines.append("")
    lines.append("## Threshold sweep (seeds + controls, replayed per "
                 "threshold)")
    lines.append("")
    lines.append("| threshold | ASR | block rate | false-hit rate | "
                 "benign completion |")
    lines.append("|---|---|---|---|---|")
    for t, m in probe.sweep():
        a, b = m["attacks"], m["benign"]
        lines.append(f"| {t:.2f} | {a['asr']:.1%} | "
                     f"{a['block_rate']:.1%} | {b['fhr']:.1%} | "
                     f"{b['completion']:.1%} |")
    lines.append("")
    lines.append("Raising the threshold to 0.99 still leaves the "
                 "exact-tier overwrite, the planted prompt asked "
                 "verbatim, and the identical-multiset role swap "
                 "succeeding — those never consult the threshold. "
                 "Lowering it to 0.80 buys no benign completion (the "
                 "two false misses are synonym paraphrases at "
                 "similarity 0.00 and 0.43, far below any usable "
                 "threshold) "
                 "and admits the short-prompt verb swap.")
    lines.append("")
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
