"""Generate adversarial_variants.jsonl from base prompts x mutations.

Meaning-changing mutations (add_negation, swap_number, swap_entity,
swap_date) produce attack cases: the mutated query's correct answer
differs from the stored one, so a hit serves the wrong response.
Meaning-preserving mutations (drop_last, scramble) produce benign
controls: the mutated query is the same question and should hit.

Deterministic: the header stamps a sha256 over the base list and the
mutations module source, and the file regenerates byte-identically.

Run from the repo root: python evals/generate_variants.py
"""

import hashlib
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from mutations import MUTATIONS  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "adversarial_variants.jsonl")

BASES = [
    {"prompt": "how do i reset my account password if i forgot it today",
     "response": "use the reset link on the sign-in page"},
    {"prompt": "what is the refund window for a damaged product return request",
     "response": "30 days"},
    {"prompt": "can i cancel my subscription today",
     "response": "yes - from the settings page"},
    {"prompt": "is the refund window thirty days for a standard return request",
     "response": "yes - the refund window is thirty days"},
    {"prompt": "how do i track my order from the chennai warehouse after dispatch",
     "response": "use the chennai dispatch tracking link"},
    {"prompt": "when will my delivery arrive if i ordered it yesterday morning",
     "response": "tomorrow by end of day"},
    {"prompt": "how do i transfer money from my savings account to my current account",
     "response": "use the transfer tab in online banking"},
    {"prompt": "how long does standard shipping usually take to arrive here",
     "response": "three to five business days"},
]

ATTACK_MUTATIONS = ("add_negation", "swap_number", "swap_entity", "swap_date")
CONTROL_MUTATIONS = ("drop_last", "scramble")


def build_cases():
    cases = []
    for base in BASES:
        for name in ATTACK_MUTATIONS:
            mutated = MUTATIONS[name](base["prompt"])
            if mutated is None:
                continue
            cases.append({
                "id": f"variant-{name}-{len(cases)}",
                "kind": "attack",
                "family": f"variant-{name}",
                "stores": [base],
                "queries": [{"prompt": mutated,
                             "poison_response": base["response"],
                             "legit_response": None}],
            })
        for name in CONTROL_MUTATIONS:
            mutated = MUTATIONS[name](base["prompt"])
            if mutated is None:
                continue
            cases.append({
                "id": f"variant-{name}-{len(cases)}",
                "kind": "control",
                "family": f"variant-{name}",
                "stores": [base],
                "query": {"prompt": mutated, "expect": "hit",
                          "response": base["response"]},
            })
    return cases


def main():
    with open(os.path.join(HERE, "mutations.py"), "rb") as f:
        stamp_src = json.dumps(BASES, sort_keys=True).encode() + f.read()
    stamp = hashlib.sha256(stamp_src).hexdigest()
    lines = [
        "# generated by evals/generate_variants.py - do not edit by hand",
        f"# bases+mutations sha256: {stamp}",
    ]
    lines += [json.dumps(c, sort_keys=True) for c in build_cases()]
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print(f"wrote {OUT}: {len(lines) - 2} cases, stamp {stamp[:12]}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
